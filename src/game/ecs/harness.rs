//! Scripted determinism regression.
//!
//! The port's behavioural-equivalence harness, reduced to the one thing worth
//! keeping permanently: a fixed set of seeded, scripted games whose state trace
//! is hashed against a golden value.
//!
//! ## Where the goldens come from
//!
//! Originally the Vec-based `World` of `review-fixes-art-mouse` 07e26c9 (with
//! `reap_enemies` patched to keep `Vec` spawn order), which the port matched
//! byte for byte on 36 scripted cases.
//!
//! **The level content update regenerated them.** Levels are now procedurally
//! generated from the run seed, so the old fixed prop grids — and with them the
//! old reference trace — are gone. The hashes below were taken from this build
//! at the commit that introduced `Level::generate` + the tile grid; they no
//! longer prove parity with the pre-port reference, only that the current
//! behaviour is frozen (same seed, same trace).
//!
//! A change to any simulated number, any rng draw or its order, or any
//! iteration-order rule moves one of these hashes. `same_seed_same_run` also
//! proves the weaker property directly (two runs of the same seed agree), which
//! catches non-determinism introduced by iteration order even if a golden were
//! ever regenerated by mistake.
//!
//! No environment variables: `cargo test` runs everything here.

use crate::game::enemy::{Enemy, EnemyKind};
use crate::game::level::Theme;
use crate::game::world::World;
use crate::math::Vec2;

/// The simulation's fixed tick, as the App and the reference harness use it.
const DT: f32 = 1.0 / 60.0;
/// 60 simulated seconds per case: long enough to reach elites, Brutes and the
/// boss-adjacent spawn curves while keeping the suite fast.
const TICKS: u64 = 3_600;
/// Sample (and fold into the trace hash) every half second.
const SAMPLE_EVERY: u64 = 30;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Script {
    /// Slow sin/cos wander, 1.5 s standstill every 15 s, dash every 157 ticks.
    Wander,
    /// Flee from the local crowd (read through the facade query snapshots),
    /// with a deterministic wander bias. Draws a much denser crowd, so it
    /// exercises separation, the enemy cap and the weapon fire far harder.
    Evade,
}

impl Script {
    fn name(self) -> &'static str {
        match self {
            Script::Wander => "wander",
            Script::Evade => "evade",
        }
    }
}

/// Deterministic scripted input (the same script in both implementations).
fn script(w: &mut World, tick: u64, mode: Script) -> (Vec2, bool) {
    let t = tick as f32;
    let phase = t * 0.013;
    let bias = Vec2::new(phase.sin(), (phase * 0.7).cos());
    let dash = tick.is_multiple_of(157);
    match mode {
        Script::Wander => {
            let dir = if tick % 900 < 90 {
                Vec2::ZERO
            } else {
                bias
            };
            (dir, dash)
        }
        Script::Evade => {
            let p = w.player.pos;
            let enemies = w.enemies();
            let mut fx = 0.0f32;
            let mut fy = 0.0f32;
            for e in &enemies {
                let dx = p.x - e.pos.x;
                let dy = p.y - e.pos.y;
                let d2 = dx * dx + dy * dy;
                if d2 < 8100.0 {
                    let d = d2.sqrt();
                    let wgt = 1.0 / (d + 8.0);
                    fx += dx * wgt;
                    fy += dy * wgt;
                }
            }
            let len = (fx * fx + fy * fy).sqrt();
            let flee = if len > 1e-4 {
                Vec2::new(fx / len, fy / len)
            } else {
                bias
            };
            let dir = Vec2::new(flee.x * 0.85 + bias.x * 0.15, flee.y * 0.85 + bias.y * 0.15);
            (dir, dash)
        }
    }
}

/// Pick the first upgrade card until no level-up is pending (what the App does
/// on the LevelUp screen, including the heal).
fn resolve_levelups(w: &mut World) {
    let mut guard = 0;
    while w.pending_levelups > 0 && !w.finished() && guard < 64 {
        guard += 1;
        let choices = w.player.loadout.generate_choices(&mut w.rng);
        let Some(up) = choices.into_iter().next() else {
            break;
        };
        let heal = w.player.loadout.apply(&up);
        w.player.heal(heal);
        w.pending_levelups = w.pending_levelups.saturating_sub(1);
    }
}

fn fold(mut h: u64, v: u64) -> u64 {
    for b in v.to_le_bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

/// Order-independent hash of every enemy's full simulated state. Sorting by
/// position keeps the hash meaningful even if a future change legitimately
/// permutes the (sanctioned) enemy iteration order.
fn enemy_hash(enemies: &[Enemy]) -> u64 {
    let mut rows: Vec<(u64, u64)> = enemies
        .iter()
        .map(|e| {
            let mut h = 0xcbf2_9ce4_8422_2325u64;
            for v in [
                e.hp.to_bits() as u64,
                e.anim.to_bits() as u64,
                e.vel.x.to_bits() as u64,
                e.vel.y.to_bits() as u64,
                e.flash.to_bits() as u64,
                e.contact_cd.to_bits() as u64,
                e.fire_cd.to_bits() as u64,
                e.kind as u32 as u64,
            ] {
                h = fold(h, v);
            }
            (
                e.pos.x.to_bits() as u64 | (e.pos.y.to_bits() as u64) << 32,
                h,
            )
        })
        .collect();
    rows.sort_unstable();
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    for (pos, row) in rows {
        h = fold(h, pos);
        h = fold(h, row);
    }
    h
}

/// One sample of the whole simulated state, folded into the running trace hash.
fn fold_state(h: u64, w: &mut World) -> u64 {
    let enemies = w.enemies();
    let (bullets, gems, pickups, pools) = (
        w.bullets().len() as u64,
        w.gems().len() as u64,
        w.pickups().len() as u64,
        w.pools().len() as u64,
    );
    let (elapsed, kills, score) = (w.elapsed, w.kills, w.score);
    let (particles, numbers) = (w.particles.len() as u64, w.damage_numbers.len() as u64);
    let p = &w.player;
    let mut h = fold(h, elapsed.to_bits() as u64);
    for v in [
        p.pos.x.to_bits() as u64,
        p.pos.y.to_bits() as u64,
        p.vel.x.to_bits() as u64,
        p.vel.y.to_bits() as u64,
        p.hp.to_bits() as u64,
        p.iframes.to_bits() as u64,
        p.dash_cd.to_bits() as u64,
        p.level as u64,
        p.xp as u64,
        p.xp_to_next as u64,
        kills as u64,
        score as u64,
        enemies.len() as u64,
        bullets,
        gems,
        pickups,
        pools,
        particles,
        numbers,
    ] {
        h = fold(h, v);
    }
    fold(h, enemy_hash(&enemies))
}

/// Run one scripted case and hash its whole trace.
fn trace_hash(script_mode: Script, theme: Theme, seed: u64) -> u64 {
    let mut w = World::new(theme, seed);
    w.viewport = Vec2::new(160.0, 168.0);
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    h = fold(h, seed);
    let mut tick = 0;
    while tick < TICKS && !w.finished() {
        if tick.is_multiple_of(SAMPLE_EVERY) {
            h = fold_state(h, &mut w);
        }
        let (dir, dash) = script(&mut w, tick, script_mode);
        w.update(DT, dir, dash);
        resolve_levelups(&mut w);
        tick += 1;
    }
    // Fold the final state and the outcome so a run that ends early (death,
    // win) is still distinguished from one that reaches the tick limit.
    let (won, over) = (w.won, w.game_over);
    h = fold_state(h, &mut w);
    fold(fold(h, won as u64), over as u64)
}

/// The cases and their hashes.
///
/// **Regenerated for the procedural-level content update**: the maps are no
/// longer the three fixed prop grids, so the pre-port reference can no longer
/// reproduce a trace. From this change on the goldens are self-generated by
/// this build, and their only job is to freeze the *current* behaviour: they
/// still catch any change in a simulated number, an rng draw or its order, or
/// an iteration-order rule, and `same_seed_same_run` / `scripted_crowd...`
/// still prove determinism and that the crowd actually grows.
///
/// **Regenerated again for the tile-collision migration** (CONTENT_PLAN §4,
/// worker D): the player, enemy, lob and spawn wall tests now query the tile
/// grid instead of the merged `Level::walls` rect list, one-way gates are
/// solid to the horde, and a spawn ring point inside a rat-hole gap is
/// rejected. Those are deliberate behaviour changes, so every case moved.
///
/// **Regenerated once more for the navigation rewrite** (CONTENT_PLAN §3,
/// worker C): enemies now follow one flow field per size class, sampled from a
/// fine window near the player (with a centreline pull that keeps bodies off
/// jambs) and a block-coarse field beyond it, and the diagonal step rule is
/// "both neighbours open" instead of "either". Those change every enemy's
/// path, hence five of six traces. Anyone whose change moves these again must
/// regenerate the whole list in the same change — never hand-edit one row.
///
/// **Regenerated again for the real level generator** (CONTENT_PLAN §2, worker
/// A): maps are no longer the placeholder arena — rooms, halls, corridors, a
/// boss arena, maze slots and their access corridors all come from
/// `levelgen::layout`, so every scripted run walks a different level and all
/// six traces move. Regenerated deliberately, in the change that altered the
/// generator.
///
/// **Regenerated again for the anti-pinning fix in the coarse flow field**
/// (worker D follow-up): a body whose coarse aim point was under it, behind a
/// wall, or in a block the coarse graph cannot express used to steer straight
/// into a wall face and stand there; the coarse direction is now a legal step
/// chosen by block-cost gradient. Every path in the coarse zone changes, so all
/// six traces move. Regenerated deliberately, in the change that fixed it.
///
/// **Regenerated for the content wave** (2026-11-20): the wave changed
/// spawning pacing, wall-aware shots, traps, one-way doors, the three bosses,
/// enemy targeting and the boss arenas, so every scripted trace moved. This
/// list was regenerated once in the integration pass that closed the wave; the
/// level generator's own follow-up regeneration supersedes it.
///
/// **Regenerated for the batch-4 combined balance pass** (2026-11-21): the
/// five parallel balance branches were merged (contact grace 0.65 s, boss
/// siege/rejoin and pools, weapon/XP retune, per-level horde knobs) and then
/// trimmed (per-level horde hp, damage ramp, elite cadence, mix, Lab speed).
/// Nobody had regenerated these rows after any of it, so every row had been
/// stale since before the merge. Only the level-1 curve is exercised by the
/// scripted cases and it was left exactly where the early-game pass put it, so
/// the rows below are the values the merged build produces; the level-2/3
/// constants never appear in a scripted trace.
///
/// **Regenerated for the open-world generator** (2026-11-21, levelgen worker):
/// the layout is no longer rooms hung off 1-2-cell corridors but a sprawl of
/// great halls and medium rooms merged through 4-10-cell openings (about 52 %
/// of the grid walkable, five times the old floor), so every scripted run walks
/// a different level. Five of six traces moved; `Evade/Kitchen/29` did not, which
/// is the one case whose short script never leaves the start area's old shape.
/// Regenerated deliberately, in the change that altered the generator.
///
/// **Regenerated for the two active weapons** (2026-11-20, "active weapons"
/// worker): `WeaponKind::TailThrash` and `WeaponKind::SonicSqueak` join the
/// level-up pool, so every scripted run's upgrade shuffle draws a different
/// card sequence, and the cases that pick one fire it on the script's dash
/// ticks (`script` presses Space every 157 ticks). Five of six traces moved;
/// `Evade/Lab/1234` did not, which is the one case whose 60 s never takes a
/// card that changes the fight. The weapons themselves are rng-neutral: the
/// active pass draws nothing unless a charged weapon is actually spent, which
/// `weapons::tests::pressing_space_without_active_weapons_changes_nothing`
/// pins down directly.
const CASES: [(Script, Theme, u64, u64); 6] = [
    (Script::Wander, Theme::Sewer, 11, 12932269707065591085),
    (Script::Wander, Theme::Kitchen, 29, 3165715698561077862),
    (Script::Wander, Theme::Lab, 1234, 15223454858069299009),
    (Script::Evade, Theme::Sewer, 11, 12037375121375801552),
    (Script::Evade, Theme::Kitchen, 29, 4706391476980409671),
    (Script::Evade, Theme::Lab, 1234, 11735825699521431248),
];

#[test]
fn scripted_runs_match_the_reference_trace() {
    // Report *every* moved hash in one go, and print the replacement rows: a
    // deliberate sim change usually moves all six, and chasing them one panic
    // at a time is how a golden list drifts out of sync with its cases.
    let mut mismatches: Vec<String> = Vec::new();
    for (script_mode, theme, seed, golden) in CASES {
        let got = trace_hash(script_mode, theme, seed);
        if got != golden {
            mismatches.push(format!(
                "    ({:?}, {:?}, {seed}, {got}), // was {golden}",
                script_mode, theme
            ));
        }
    }
    assert!(
        mismatches.is_empty(),
        "trace changed for {} of {} case(s); replacement rows:\n{}",
        mismatches.len(),
        CASES.len(),
        mismatches.join("\n")
    );
}

/// The weaker property, proven directly: two runs of the same seed agree tick
/// for tick. Cheap (one sixth of a full case) and catches any non-determinism
/// that a regenerated golden would otherwise hide.
#[test]
fn same_seed_same_run() {
    for (script_mode, theme, seed, _) in CASES.iter().take(3) {
        let a = trace_hash(*script_mode, *theme, *seed);
        let b = trace_hash(*script_mode, *theme, *seed);
        assert_eq!(a, b, "same seed diverged for {theme:?} seed {seed}");
    }
}

/// The scripted crowd must actually grow: a regression that stops spawning
/// would keep the hashes stable (all zero) and silently pass.
///
/// The threshold is 15, not the 40 it was first written at, because it
/// measures the *script*, not the curve: `Script::Evade` never turns into the
/// horde, so it only ever meets the ten or so bodies that close on it in its
/// first minute, and the opening deliberately stays calm (1.2 → 3.3 enemies a
/// second over that minute; the 2025-11 balance pass kept the first 60 s as a
/// teaching stretch). The real run's peak is measured elsewhere and is far
/// higher: a bot run has ~40 live enemies at 60 s and saturates the 600 cap by
/// ~180 s, and `director::tests::the_curve_fills_a_map_ten_times_larger`
/// asserts the spawn-rate curve itself. Re-baselined 2026-11 by the early-game
/// balance worker; raise it again only together with the opening curve.
#[test]
fn scripted_crowd_reaches_the_cap_curve() {
    let mut w = World::new(Theme::Sewer, 11);
    w.viewport = Vec2::new(160.0, 168.0);
    let mut peak = 0usize;
    for tick in 0..TICKS {
        let (dir, dash) = script(&mut w, tick, Script::Evade);
        w.update(DT, dir, dash);
        resolve_levelups(&mut w);
        peak = peak.max(w.enemies().len());
        if w.finished() {
            break;
        }
    }
    // The 15-minute curve opens at 0.8→1.5 bodies/s, so 60 s of the Evade
    // script (which kills as it flees) holds a smaller peak than the old
    // 300 s curve did. The trace is still non-vacuous as long as the crowd
    // and a second kind appear.
    assert!(
        peak >= 8,
        "crowd never grew (peak {peak}): the trace cases would be vacuous"
    );
    assert!(
        w.enemies().iter().any(|e| e.kind != EnemyKind::Skitterer),
        "only one enemy kind ever spawned"
    );
}
